/**
 * GET /api/soc — entity-level State Owned Corporation statement lines.
 *
 * This is a separate layer from government program spending and from the PNFC
 * sector benchmark. It returns published rows only and computes **no total**:
 * statement lines overlap (total revenue includes separately shown grants,
 * total expenses includes employee/depreciation/transfer lines), so summing
 * them is invalid. Rows flagged `potential_double_count` name a government
 * agency or a government contribution and must never be added to government
 * program spending. Each SOC entity (Sydney Water, WaterNSW, Hunter Water, Essential Energy, Forestry Corporation of NSW, Landcom, Port Authority of NSW, TAHE, Sydney Trains, NSW TrainLink, Energy Queensland, CS Energy, Stanwell, Powerlink Queensland, Sunwater Limited and Gladstone Ports Corporation Limited and Port of Townsville Limited and Ports North NQBP Water Corporation, Synergy, Western Power, Horizon Power, Fremantle Ports and DevelopmentWA) is a separate
 * source and is never summed with the others. NSW and QLD entities are different legal populations and are never combined; Energy Queensland, CS Energy, Stanwell, Powerlink Queensland, Sunwater Limited and Gladstone Ports Corporation Limited and Port of Townsville Limited and Ports North and NQBP are separate QLD GOCs and are never added together. Water Corporation, Synergy, Western Power, Horizon Power, Fremantle Ports and DevelopmentWA are WA Government Trading Enterprises and are never combined with them.
 *
 * WaterNSW deep detail adds note-level components (`soc_note`,
 * `soc_component_of`, `soc_breakdown`). They are grouped for the UI but are
 * still non-additive: each component sums to its printed note subtotal, never
 * to the entity total. Counts are returned per section/note; no sum is
 * computed.
 */

