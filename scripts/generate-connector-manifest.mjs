#!/usr/bin/env node
/**
 * Discover connector modules and generate the imports/spread used by the
 * registry. A module is any `server/src/connectors/<id>/index.ts` (excluding the
 * shared `gpfs` engine and SOC subtree) that exports `connectorModule`.
 */
import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve('server/src/connectors');
const dirs = readdirSync(root, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .filter((name) => name !== 'gpfs' && name !== 'soc')
  .filter((name) => existsSync(path.join(root, name, 'index.ts')))
  .sort();

const imports = dirs
  .map((dir, index) => {
    const name = `module${index}`;
    return `import { connectorModule as ${name} } from './${dir}/index.js';`;
  })
  .join('\n');
const entries = dirs.map((_, index) => `module${index}`).join(', ');
const content = `// Generated by scripts/generate-connector-manifest.mjs. Do not edit by hand.
${imports}

export const MODULAR_CONNECTOR_MODULES = [${entries}] as const;
export const MODULAR_CONNECTORS = MODULAR_CONNECTOR_MODULES.map((module) => module.create());
export const MODULAR_CONNECTOR_IDS = MODULAR_CONNECTOR_MODULES.map((module) => module.id);
`;
writeFileSync(path.join(root, 'generated-connectors.ts'), content);
console.log(`[generate-connectors] modules=${dirs.length}: ${dirs.join(', ')}`);
